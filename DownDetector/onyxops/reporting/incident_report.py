import json
import os
from datetime import datetime
from onyxops.core.models import DeepScanReport

class IncidentReporter:
    """Generates structured incident reports in Markdown and JSON formats."""

    def __init__(self, output_dir: str = "incidents"):
        self.output_dir = output_dir
        os.makedirs(self.output_dir, exist_ok=True)

    def save_report(self, report: DeepScanReport) -> str:
        timestamp_slug = report.timestamp.strftime("%Y%m%d_%H%M%S")
        filename_base = f"{report.target_id}_{timestamp_slug}"

        # 1. Save JSON Report
        json_path = os.path.join(self.output_dir, f"{filename_base}.json")
        data = {
            "target_id": report.target_id,
            "target_name": report.target_name,
            "url": report.url,
            "timestamp": report.timestamp.isoformat(),
            "root_cause_summary": report.root_cause_summary,
            "uptime": {
                "is_up": report.uptime.is_up,
                "status_code": report.uptime.status_code,
                "response_time_ms": report.uptime.response_time_ms,
                "dns_ips": report.uptime.dns_resolved_ips,
                "error": report.uptime.error_message,
                "ssl": {
                    "valid": report.uptime.ssl_info.valid if report.uptime.ssl_info else None,
                    "days_until_expiry": report.uptime.ssl_info.days_until_expiry if report.uptime.ssl_info else None,
                    "issuer": report.uptime.ssl_info.issuer if report.uptime.ssl_info else None
                } if report.uptime.ssl_info else None
            },
            "cloudflare": {
                "is_cloudflare": report.cloudflare.is_cloudflare,
                "cf_ray": report.cloudflare.cf_ray,
                "origin_vs_edge": report.cloudflare.origin_vs_edge,
                "cf_error_code": report.cloudflare.cf_error_code,
                "cf_error_meaning": report.cloudflare.cf_error_meaning
            },
            "open_ports": [{"port": p.port, "service": p.service, "state": p.state} for p in report.open_ports],
            "security_findings": [
                {
                    "severity": f.severity,
                    "category": f.category,
                    "title": f.title,
                    "detail": f.detail,
                    "remediation": f.remediation
                }
                for f in report.security_findings
            ]
        }

        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)

        # 2. Save Markdown Post-Mortem Report
        md_path = os.path.join(self.output_dir, f"{filename_base}.md")
        md_content = self._render_markdown(report)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        return md_path

    def _render_markdown(self, report: DeepScanReport) -> str:
        findings_rows = ""
        for f in report.security_findings:
            findings_rows += f"| **{f.severity}** | {f.category} | {f.title} | {f.remediation} |\n"

        ports_rows = ""
        for p in report.open_ports:
            ports_rows += f"| `{p.port}` | {p.service} | {p.state} |\n"

        final_ports = ports_rows if ports_rows else "| None | No abnormal open ports found | - |\n"
        final_findings = findings_rows if findings_rows else "| INFO | None | Clean scan - no common vulnerabilities detected | N/A |\n"
        ssl_desc = "N/A"
        if report.uptime.ssl_info:
            if report.uptime.ssl_info.valid:
                ssl_desc = f"Valid ({report.uptime.ssl_info.days_until_expiry} days remaining)"
            else:
                ssl_desc = report.uptime.ssl_info.error_message or "Invalid"

        return f"""# Incident Forensic Report: {report.target_name}
**Generated by OnyxOps Sentinel (WolfeGuard)**
**Developer:** sinfulldesirez
**Incident Timestamp:** {report.timestamp.strftime("%Y-%m-%d %H:%M:%S UTC")}

---

## 1. Executive Summary
- **Target URL:** {report.url}
- **Status:** {'UP' if report.uptime.is_up else 'DOWN'}
- **HTTP Status Code:** {report.uptime.status_code or 'NO RESPONSE'}
- **Response Latency:** {report.uptime.response_time_ms} ms
- **Root Cause Determination:** {report.root_cause_summary}

---

## 2. Cloudflare & Edge Diagnostic
- **Cloudflare Protected:** {'Yes' if report.cloudflare.is_cloudflare else 'No'}
- **Ray ID:** `{report.cloudflare.cf_ray or 'N/A'}`
- **Edge Status:** {report.cloudflare.origin_vs_edge}
- **Diagnostic Details:** {report.cloudflare.cf_error_meaning or 'None'}

---

## 3. Network & Infrastructure
- **Resolved IPs:** {', '.join(report.uptime.dns_resolved_ips) or 'DNS Resolution Failed'}
- **SSL Certificate:** {ssl_desc}

### Open Ports Audit
| Port | Service | State |
|------|---------|-------|
{final_ports}
---

## 4. Deep Security & Intrusion Findings ({len(report.security_findings)})
| Severity | Category | Vulnerability / Issue | Remediation |
|----------|----------|-----------------------|-------------|
{final_findings}
---
*Report archived automatically by OnyxOps Sentinel Incident Engine.*
"""
